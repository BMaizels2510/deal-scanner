// Turns data/catalogue.json into seed.sql: sets, products, latest market, a dated snapshot, and eBay searches.
// Re-running it after a refresh updates prices and adds another day of history; it never deletes history.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const cat = JSON.parse(readFileSync(new URL("../data/catalogue.json", import.meta.url), "utf8"));
const q = v => v == null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const row = vals => `(${vals.map(q).join(",")})`;
const day = cat.updated_at.slice(0, 10);
const col = Object.fromEntries(cat.columns.map((c, i) => [c, i]));

export function parseProduct(r) {
  const id = r[col.id];
  const [type, rest] = id.split(/:(.*)/s);
  const parts = rest.split("|");
  const set_id = parts[0];
  const nul = v => (v === "null" || v === "" || v == null ? null : v);
  if (type === "sealed") {
    return { id, set_id, kind: "sealed", material: null, promo: null, grader: null, grade: null, card_key: null };
  }
  const material = nul(parts[2]), promo = nul(parts[3]), grader = nul(parts[4]), grade = nul(parts[5]);
  return { id, set_id, kind: grader ? "slab" : "raw", material, promo, grader, grade, card_key: [set_id, parts[1], parts[2], parts[3]].join("|") };
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) build();

function build() {
const products = cat.products.map(r => ({ ...parseProduct(r), r }));
const rawUrlByCard = Object.fromEntries(products.filter(p => p.kind === "raw" && p.r[col.url]).map(p => [p.card_key, p.r[col.url]]));
const pulseUrl = p => {
  let slug = p.r[col.url];
  if (slug === "" && p.kind === "slab" && rawUrlByCard[p.card_key]) slug = `${rawUrlByCard[p.card_key]}-${p.grader.toLowerCase()}-${p.grade}`;
  if (!slug) return null;
  return `https://pulsetcg.io/${p.kind === "sealed" ? "sealed" : "cards"}/${slug}`;
};

const out = ["-- Generated by scripts/build-seed.mjs from data/catalogue.json. Edit that file instead."];

for (const [id, s] of Object.entries(cat.sets)) {
  out.push(`INSERT INTO sets (id,name,q,released,vintage) VALUES ${row([id, s.name, s.q, s.released || null, s.vintage ? 1 : 0])}
  ON CONFLICT(id) DO UPDATE SET name=excluded.name, q=excluded.q, released=excluded.released, vintage=excluded.vintage;`);
}

// Products no longer in the catalogue are switched off, not deleted (their deals keep working).
out.push("UPDATE products SET active = 0;");
for (const p of products) {
  const r = p.r;
  out.push(`INSERT INTO products (id,name,set_id,number,kind,category,material,promo,grader,grade,card_key,p10,lp,pulse_url,active) VALUES ${row([
    p.id, r[col.name], p.set_id, r[col.number], p.kind, r[col.cat], p.material, p.promo, p.grader, p.grade, p.card_key, r[col.p10], r[col.lp], pulseUrl(p), 1,
  ])}
  ON CONFLICT(id) DO UPDATE SET name=excluded.name, number=excluded.number, category=excluded.category, p10=COALESCE(excluded.p10, products.p10),
    lp=COALESCE(excluded.lp, products.lp), pulse_url=COALESCE(excluded.pulse_url, products.pulse_url), active=1;`);
  if (p.kind === "raw" && col.mp != null && [r[col.lp], r[col.mp], r[col.hp]].some(v => v != null)) {
    out.push(`INSERT OR REPLACE INTO cond_prices (product_id,lp,mp,hp,updated_at) VALUES ${row([p.id, r[col.lp] ?? null, r[col.mp] ?? null, r[col.hp] ?? null, cat.updated_at])};`);
  }
  const m = [r[col.market], r[col.t7], r[col.t30], r[col.s7], r[col.s30], r[col.src]];
  out.push(`INSERT OR REPLACE INTO market (product_id,market,t7,t30,s7,s30,src,source,updated_at) VALUES ${row([p.id, ...m, "pulse", cat.updated_at])};`);
  out.push(`INSERT OR REPLACE INTO market_snapshots (product_id,at,market,t7,t30,s7,s30,src) VALUES ${row([p.id, cat.updated_at, ...m])};`);
}

// eBay searches, one per distinct search phrase (sets sharing a phrase, like the Base Set editions, share a search).
// Sets that only hold Special Illustration Rares search for "SIR" or "Illustration" in the title; sealed products get their own search.
const bySearch = {};
for (const [id, s] of Object.entries(cat.sets)) (bySearch[s.q] ||= []).push(id);
out.push("UPDATE searches SET active = 0;");
let searchCount = 0;
const addSearch = (id, q, setIds, list) => {
  if (!list.length) return;
  const min = Math.max(8, Math.floor(Math.min(...list.map(p => p.r[col.market])) * 0.35));
  out.push(`INSERT INTO searches (id,q,set_ids,min_price,active) VALUES ${row([id, q, JSON.stringify(setIds), min, 1])}
  ON CONFLICT(id) DO UPDATE SET q=excluded.q, set_ids=excluded.set_ids, min_price=excluded.min_price, active=1;`);
  searchCount++;
};
for (const [phrase, setIds] of Object.entries(bySearch)) {
  const inSets = products.filter(p => setIds.includes(p.set_id));
  const cards = inSets.filter(p => p.kind !== "sealed"), sealed = inSets.filter(p => p.kind === "sealed");
  const sirOnly = cards.length && cards.every(p => p.r[col.cat] === "sir");
  addSearch(setIds.join("+"), `pokemon ${phrase}${sirOnly ? " (sir, illustration)" : ""}`, setIds, cards);
  addSearch(setIds.join("+") + ":sealed", `pokemon ${phrase} (booster, etb, elite, bundle)`, setIds, sealed);
}

writeFileSync(new URL("../seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed.sql written: ${products.length} products, ${Object.keys(cat.sets).length} sets, ${searchCount} searches, snapshot ${day}`);
}
